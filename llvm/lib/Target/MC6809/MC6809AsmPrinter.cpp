class MC6809AsmPrinter : public AsmPrinter {
  MC6809MCInstLower InstLowering;

public:
  explicit MC6809AsmPrinter(TargetMachine &TM, std::unique_ptr<MCStreamer> Streamer) : AsmPrinter(TM, std::move(Streamer)), InstLowering(OutContext, *this) {}

  // Generated by TableGen.
  bool lowerPseudoInstExpansion(const MachineInstr *MI, MCInst &Inst);

  // Wrapper needed for tblgenned pseudo lowering.
  void lowerOperand(const MachineOperand &MO, MCOperand &MCOp);

  void EmitToStreamer(MCStreamer &S, MCInst &Inst);

  void emitInstruction(const MachineInstr *MI) override;

  bool PrintAsmOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) override;

  bool PrintAsmMemoryOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) override;

  void emitStartOfAsmFile(Module &M) override;

  void emitJumpTableInfo() override;

  const MCSymbol *getFunctionFrameSymbol(int FI) const override;
};

// Simple pseudo-instructions have their lowering (with expansion to real
// instructions) auto-generated.
#include "MC6809GenMCPseudoLowering.inc"

void MC6809AsmPrinter::EmitToStreamer(MCStreamer &S, MCInst &Inst) {
  // If this instruction contains an out-of-range immediate address, perform an
  // early relax.
  MC6809AsmBackend::relaxForImmediate(Inst, MF->getSubtarget<MC6809Subtarget>());
  AsmPrinter::EmitToStreamer(S, Inst);
}

void MC6809AsmPrinter::emitInstruction(const MachineInstr *MI) {
  // Bug #186 v5 PLACEHOLDER (2026-04-27): COPY_CC_PLACEHOLDER expands
  // to a comment + SWI3 trap. Emitted by copyPhysReg's fallback path
  // for register pairs we don't have a proper sequence for yet
  // (chiefly $c↔byte / $v↔byte / cross-flag pairs). Runtime hits
  // surface noisily via SWI3; asm-grep on `; PLACEHOLDER COPY` finds
  // every emission site so we can decide which class pairs to wire up
  // properly in copyPhysReg.
  if (MI->getOpcode() == MC6809::COPY_CC_PLACEHOLDER) {
    const TargetRegisterInfo *TRI =
        MI->getMF()->getSubtarget().getRegisterInfo();
    std::string Dst = TRI->getName(MI->getOperand(0).getReg());
    std::string Src = TRI->getName(MI->getOperand(1).getReg());
    OutStreamer->AddComment("PLACEHOLDER COPY $" + Dst + " <- $" + Src
                            + " (bug #186 v5)");
    MCInst SWI;
    SWI.setOpcode(MC6809::SWI3x);
    EmitToStreamer(*OutStreamer, SWI);
    return;
  }
  // Do any auto-generated pseudo lowerings.
  if (MCInst OutInst; lowerPseudoInstExpansion(MI, OutInst)) {
    EmitToStreamer(*OutStreamer, OutInst);
    return;
  }
  // BranchJumpTable: expand to a position-independent jump-table
  // dispatch sequence.
  //
  //   ASLB             ; D = index * 2 (each entry is 2 bytes)
  //   ROLA
  //   LEAX JT,PCR      ; X = jump table base, PC-relative
  //   LDD D,X          ; D = JT[index] (rel offset from JT base)
  //   JMP D,X          ; jump to JT base + offset
  //
  // The $idx operand must already be in $ad by the time we get here —
  // see the BranchJumpTable definition (operand class ADc) and
  // MC6809MaterializeSpills (which materializes any SPILL_D operand
  // into AD with an LDD before this instruction). Assert it as a
  // tripwire for any future regression of bug #68.
  //
  // The whole sequence stays position-independent: jump table entries
  // are emitted as `.short Lcase - LJTbase` (relative offsets), and
  // the LEAX uses `,PCR` to compute the table base relative to PC.
  // Together with the `LDXi16` opcode for `LDX #JT` being avoided,
  // there are no absolute addresses anywhere in the dispatch — the
  // whole thing can be relocated by an OS-9-style loader.
  //
  // History note (bug #68): the obvious LEAXi_o16PC choice loses its
  // size info through the textual `.s` intermediate (the asm parser
  // accepted any symbol ref as PCRel8 too, and the matcher picked
  // the smaller form). The fix is in the parser (isPCRel8 now
  // rejects symbol refs), so the assembler always picks the 16-bit
  // form for symbolic operands. With that fix in place, this
  // expansion can use the original PCR-relative LEAX cleanly.
  if (MI->getOpcode() == MC6809::BranchJumpTable) {
    assert(MI->getOperand(0).isReg() &&
           MI->getOperand(0).getReg() == MC6809::AD &&
           "BranchJumpTable: $idx must be in $ad before expansion (bug #68)");
    unsigned JTI = MI->getOperand(1).getIndex();
    MCSymbol *JTSym = GetJTISymbol(JTI);
    // ASLB — shift index left (low byte)
    MCInst ASL;
    ASL.setOpcode(MC6809::ASLBa);
    EmitToStreamer(*OutStreamer, ASL);
    // ROLA — shift index left (high byte with carry)
    MCInst ROL;
    ROL.setOpcode(MC6809::ROLAa);
    EmitToStreamer(*OutStreamer, ROL);
    // LEAX JT,PCR — PC-relative jump table base
    MCInst LEA;
    LEA.setOpcode(MC6809::LEAXi_o16PC);
    LEA.addOperand(MCOperand::createExpr(
        MCSymbolRefExpr::create(JTSym, OutContext)));
    EmitToStreamer(*OutStreamer, LEA);
    // LDD D,X — load relative offset from table[index]
    MCInst LDD;
    LDD.setOpcode(MC6809::LDDi_oD);
    LDD.addOperand(MCOperand::createReg(MC6809::IX));
    EmitToStreamer(*OutStreamer, LDD);
    // JMP D,X — jump to table base + offset
    MCInst JMP;
    JMP.setOpcode(MC6809::JMPi_oD);
    JMP.addOperand(MCOperand::createReg(MC6809::IX));
    EmitToStreamer(*OutStreamer, JMP);
    return;
  }

  if (MI->isBundle()) {
    MachineBasicBlock::const_instr_iterator I = MI->getIterator();
    MachineBasicBlock::const_instr_iterator E = MI->getParent()->instr_end();
    while (++I != E && I->isInsideBundle()) {
        MCInst Inst;
        InstLowering.lower(&*I, Inst);
        EmitToStreamer(*OutStreamer, Inst);
    }
  } else {
    MCInst Inst;
    InstLowering.lower(MI, Inst);
    EmitToStreamer(*OutStreamer, Inst);
  }
}

void MC6809AsmPrinter::lowerOperand(const MachineOperand &MO, MCOperand &MCOp) {
  if (!InstLowering.lowerOperand(MO, MCOp))
    llvm_unreachable("Failed to lower operand.");
}

bool MC6809AsmPrinter::PrintAsmOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) {
  if (!AsmPrinter::PrintAsmOperand(MI, OpNo, ExtraCode, OS))
    return false;

  const MachineOperand &MO = MI->getOperand(OpNo);
  const MC6809RegisterInfo &TRI = *MO.getParent()->getMF()->getSubtarget<MC6809Subtarget>().getRegisterInfo();

  switch (MO.getType()) {
  default:
    errs() << "Unsupported inline asm operand: " << MO << "\n";
    return true;
  case MachineOperand::MO_Immediate:
    OS << MO.getImm();
    break;
  case MachineOperand::MO_GlobalAddress:
    OS << MO.getGlobal()->getName();
    break;
  case MachineOperand::MO_Register:
    Register Reg = MO.getReg();
    OS << TRI.getRegAsmName(Reg);
    break;
  }
  return false;
}

bool MC6809AsmPrinter::PrintAsmMemoryOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) {
  // Memory operands are simply stored in pointer registers; no extra work is
  // required.
  return PrintAsmOperand(MI, OpNo, ExtraCode, OS);
}

void MC6809AsmPrinter::emitStartOfAsmFile(Module &M) {
  // Direct page pseudo-registers (__rc0..__rc31) are not currently used
  // by the GlobalISel backend. Emitting .directpage directives for them
  // crashes the ELF streamer (MCSymbolELF::setOther assertion). Disabled
  // until the direct page allocator pass is implemented.
}

void MC6809AsmPrinter::emitJumpTableInfo() {
  const DataLayout &DL = MF->getDataLayout();
  const MachineJumpTableInfo *MJTI = MF->getJumpTableInfo();
  if (!MJTI)
    return;
  assert(MJTI->getEntryKind() == MachineJumpTableInfo::EK_BlockAddress);
  const std::vector<MachineJumpTableEntry> &JT = MJTI->getJumpTables();
  if (JT.empty())
    return;

  // Jump table must be in the same section as the function for PIC label
  // differences to resolve correctly. Don't switch to .rodata.

  emitAlignment(Align(MJTI->getEntryAlignment(DL)));

  // Mark the data region in the code section.
  OutStreamer->emitDataRegion(MCDR_DataRegionJT32);

  for (const auto &JTI : enumerate(JT)) {
    const std::vector<MachineBasicBlock *> &JTBBs = JTI.value().MBBs;

    // If this jump table was deleted, ignore it.
    if (JTBBs.empty())
      continue;

    MCSymbol *JTISymbol = GetJTISymbol(JTI.index());
    OutStreamer->emitLabel(JTISymbol);

    // Emit an array of offsets from the table base (PIC).
    // Each entry is (target - table_base), so JMP D,X reaches the target.
    //
    // Bug #145: mask the difference with 0xFFFF. The runtime dispatch
    // (`JMP D,X` with D = JT[idx], X = table base) computes
    //   PC = (X + D) mod 2^16
    // so any value congruent to (target - table_base) mod 2^16 is
    // correct — including negative values when the target sits below
    // the table base in the linker layout. The MC encoder's range
    // check in MCObjectStreamer::emitValueImpl rejects diffs whose
    // signed value is outside [-32768, 32767] AND whose unsigned
    // value is outside [0, 65535]; for backward jumps spanning
    // > 32 KB the int64 difference is negative and out-of-range,
    // failing the check. Masking to uint16 keeps the assembled byte
    // pair identical (since `JMP D,X` ignores any high bits) while
    // landing the encoder check in [0, 65535]. Manifested at -Og in
    // strftime — at higher opt levels the function shrinks enough
    // that the target/base distance stays inside signed-16 range.
    const MCExpr *TableBase = MCSymbolRefExpr::create(JTISymbol, OutContext);
    const MCExpr *Mask = MCConstantExpr::create(0xFFFF, OutContext);
    for (const MachineBasicBlock *JTBB : JTBBs) {
      const MCExpr *Target = MCSymbolRefExpr::create(JTBB->getSymbol(), OutContext);
      const MCExpr *Diff = MCBinaryExpr::createSub(Target, TableBase, OutContext);
      const MCExpr *Masked = MCBinaryExpr::createAnd(Diff, Mask, OutContext);
      OutStreamer->emitValue(Masked, 2);
    }
  }
  OutStreamer->emitDataRegion(MCDR_DataRegionEnd);
}

const MCSymbol *MC6809AsmPrinter::getFunctionFrameSymbol(int FI) const {
  // Bug #387: a static-stack frame index resolves to this function's
  // static-stack global (set by MC6809StaticStackAlloc), not the dynamic
  // frame pointer.
  if (MF->getFrameInfo().getStackID(FI) == TargetStackID::Mc6809Static) {
    const auto &MFI = *MF->getInfo<MC6809FunctionInfo>();
    if (MFI.StaticStackValue)
      return getSymbol(MFI.StaticStackValue);
  }
  return AsmPrinter::getFunctionFrameSymbol(FI);
}

