class MC6809AsmPrinter : public AsmPrinter {
  MC6809MCInstLower InstLowering;

public:
  explicit MC6809AsmPrinter(TargetMachine &TM, std::unique_ptr<MCStreamer> Streamer) : AsmPrinter(TM, std::move(Streamer)), InstLowering(OutContext, *this) {}

  // Generated by TableGen.
  bool lowerPseudoInstExpansion(const MachineInstr *MI, MCInst &Inst);

  // Wrapper needed for tblgenned pseudo lowering.
  void lowerOperand(const MachineOperand &MO, MCOperand &MCOp);

  void EmitToStreamer(MCStreamer &S, MCInst &Inst);

  void emitInstruction(const MachineInstr *MI) override;

  bool PrintAsmOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) override;

  bool PrintAsmMemoryOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) override;

  void emitStartOfAsmFile(Module &M) override;

  void emitJumpTableInfo() override;

  const MCSymbol *getFunctionFrameSymbol(int FI) const override;
};

// Simple pseudo-instructions have their lowering (with expansion to real
// instructions) auto-generated.
#include "MC6809GenMCPseudoLowering.inc"

void MC6809AsmPrinter::EmitToStreamer(MCStreamer &S, MCInst &Inst) {
  // If this instruction contains an out-of-range immediate address, perform an
  // early relax.
  MC6809AsmBackend::relaxForImmediate(Inst, MF->getSubtarget<MC6809Subtarget>());
  AsmPrinter::EmitToStreamer(S, Inst);
}

void MC6809AsmPrinter::emitInstruction(const MachineInstr *MI) {
  // Do any auto-generated pseudo lowerings.
  if (MCInst OutInst; lowerPseudoInstExpansion(MI, OutInst)) {
    EmitToStreamer(*OutStreamer, OutInst);
    return;
  }
  // BranchJumpTable: expand to PIC jump table sequence.
  // ASLB+ROLA (index*2), LEAX table,PCR, JMP [D,X]
  if (MI->getOpcode() == MC6809::BranchJumpTable) {
    unsigned JTI = MI->getOperand(1).getIndex();
    MCSymbol *JTSym = GetJTISymbol(JTI);
    // ASLB — shift index left (low byte)
    MCInst ASL;
    ASL.setOpcode(MC6809::ASLBa);
    EmitToStreamer(*OutStreamer, ASL);
    // ROLA — shift index left (high byte with carry)
    MCInst ROL;
    ROL.setOpcode(MC6809::ROLAa);
    EmitToStreamer(*OutStreamer, ROL);
    // LEAX table,PCR — PC-relative table base address
    MCInst LEA;
    LEA.setOpcode(MC6809::LEAXi_o16PC);
    LEA.addOperand(MCOperand::createExpr(
        MCSymbolRefExpr::create(JTSym, OutContext)));
    EmitToStreamer(*OutStreamer, LEA);
    // LDD D,X — load relative offset from table[index]
    MCInst LDD;
    LDD.setOpcode(MC6809::LDDi_oD);
    LDD.addOperand(MCOperand::createReg(MC6809::IX));
    EmitToStreamer(*OutStreamer, LDD);
    // JMP D,X — jump to table base + offset (PIC)
    MCInst JMP;
    JMP.setOpcode(MC6809::JMPi_oD);
    JMP.addOperand(MCOperand::createReg(MC6809::IX));
    EmitToStreamer(*OutStreamer, JMP);
    return;
  }

  if (MI->isBundle()) {
    MachineBasicBlock::const_instr_iterator I = MI->getIterator();
    MachineBasicBlock::const_instr_iterator E = MI->getParent()->instr_end();
    while (++I != E && I->isInsideBundle()) {
        MCInst Inst;
        InstLowering.lower(&*I, Inst);
        EmitToStreamer(*OutStreamer, Inst);
    }
  } else {
    MCInst Inst;
    InstLowering.lower(MI, Inst);
    EmitToStreamer(*OutStreamer, Inst);
  }
}

void MC6809AsmPrinter::lowerOperand(const MachineOperand &MO, MCOperand &MCOp) {
  if (!InstLowering.lowerOperand(MO, MCOp))
    llvm_unreachable("Failed to lower operand.");
}

bool MC6809AsmPrinter::PrintAsmOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) {
  if (!AsmPrinter::PrintAsmOperand(MI, OpNo, ExtraCode, OS))
    return false;

  const MachineOperand &MO = MI->getOperand(OpNo);
  const MC6809RegisterInfo &TRI = *MO.getParent()->getMF()->getSubtarget<MC6809Subtarget>().getRegisterInfo();

  switch (MO.getType()) {
  default:
    errs() << "Unsupported inline asm operand: " << MO << "\n";
    return true;
  case MachineOperand::MO_Immediate:
    OS << MO.getImm();
    break;
  case MachineOperand::MO_GlobalAddress:
    OS << MO.getGlobal()->getName();
    break;
  case MachineOperand::MO_Register:
    Register Reg = MO.getReg();
    OS << TRI.getRegAsmName(Reg);
    break;
  }
  return false;
}

bool MC6809AsmPrinter::PrintAsmMemoryOperand(const MachineInstr *MI, unsigned OpNo, const char *ExtraCode, raw_ostream &OS) {
  // Memory operands are simply stored in pointer registers; no extra work is
  // required.
  // XXXX: FIXME: MarkM - Really? I'll be the judge of that.
  return PrintAsmOperand(MI, OpNo, ExtraCode, OS);
}

