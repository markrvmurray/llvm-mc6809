#include "llvm/CodeGen/GlobalISel/LegalizerInfo.h"
#include "llvm/CodeGen/RegisterBankInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"

#define GET_SUBTARGETINFO_HEADER
#include "MC6809GenSubtargetInfo.inc"

namespace llvm {
class MC6809TargetMachine;

class MC6809Subtarget final : public MC6809GenSubtargetInfo {
  /// What processor and OS we're targeting.
  Triple TargetTriple;

  /// True if compiling for HD6309 false for MC6809
  bool Has6309Ops;

  // Ordering here is important. MC6809InstrInfo initializes MC6809RegisterInfo which
  // MC6809TargetLowering needs.
  MC6809InstrInfo InstrInfo;
  MC6809TargetLowering TLInfo;
  MC6809FrameLowering FrameLowering;

  /// GlobalISel related APIs.
  std::unique_ptr<MC6809CallLowering> CallLoweringInfo;
  // std::unique_ptr<MC6809InlineAsmLowering> InlineAsmLoweringInfo;
  std::unique_ptr<InstructionSelector> InstSelector;
  std::unique_ptr<MC6809LegalizerInfo> Legalizer;
  std::unique_ptr<MC6809RegisterBankInfo> RegBankInfo;

public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
  MC6809Subtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU, StringRef FS, const MC6809TargetMachine &TM);

  /// Gets the e_flags value of an ELF object file.
  unsigned getEFlags() const {
    assert(EFlags != 0 && "every MC6809 subtarget must set at least one architecture feature");
      return EFlags;
  }

  const MC6809TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const MC6809InstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const MC6809FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const MC6809RegisterInfo *getRegisterInfo() const override {
    return &getInstrInfo()->getRegisterInfo();
  }

  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  /// Methods used by Global ISel
  const MC6809CallLowering *getCallLowering() const override {
    return CallLoweringInfo.get();
  }
#if 0
  const MC6809InlineAsmLowering *getInlineAsmLowering() const override {
    return InlineAsmLoweringInfo.get();
  }
#endif
  InstructionSelector *getInstructionSelector() const override {
    return InstSelector.get();
  }
  const LegalizerInfo *getLegalizerInfo() const override {
    return Legalizer.get();
  }
  const RegisterBankInfo *getRegBankInfo() const override {
    return RegBankInfo.get();
  }

private:
  /// The ELF e_flags architecture features.
  unsigned EFlags = 0;

  // Dummy member, used by FeatureSet's. We cannot have a SubtargetFeature with
  // no variable, so we instead bind pseudo features to this variable.
  bool FeatureSetDummy = false;

  bool LongRegisterNames = false;

  MC6809Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef TuneCPU, StringRef FS);
  void initializeEnvironment();

public:
  const Triple &getTargetTriple() const { return TargetTriple; }
  bool isHD6309() const { return Has6309Ops; }
};
} // namespace llvm

#endif
